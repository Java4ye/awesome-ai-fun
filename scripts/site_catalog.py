"""Build the static gallery catalog from the same records as the README."""
import json
from collections import defaultdict
from pathlib import Path
from showcase import CATEGORY_NAMES, collection_entries, play_link, resolve_showcase


def render_site_catalog(cases, sources, history, records):
    covers=resolve_showcase(history,records)
    entries,groups,prompts=collection_entries(cases)
    by_id={c['id']:c for c in cases}
    by_source={s['id']:s for s in sources}
    runs=defaultdict(list)
    for row in history:
        runs[row['case_id']].append(row)

    def media(cid):
        c=by_id[cid];p=covers.get(cid,{})
        first=next(iter(runs[cid]),{})
        local=p.get('preview') or p.get('capture')
        image='../'+local if local else p.get('image_url')
        source=p.get('source_url') or c['source_url']
        output=p.get('output_url') or first.get('output_url') or source
        play=play_link(cid,output)
        return {
            'id':cid,'title':[c['title'],c['title_en']],
            'publisher':p.get('publisher') or first.get('publisher') or by_source[c['source_id']]['name'],
            'image':image,'imageSource':p.get('preview_source_url') or p.get('image_url') or output,
            'source':source,'output':output,'video':p.get('video_url'),
            'play':play,'guide':c.get('guide_url'),'tools':p.get('model') or first.get('model'),
            'note':[p.get('note',''),p.get('note_en','')],
        }

    works=[]
    for c in entries:
        cid=c['id'];group=groups.get(cid)
        members=group[1] if group else (cid,)
        examples=group[2] if group else members
        variants=[media(i) for i in members]
        main=next((v for i in examples for v in variants if v['id']==i and v['image']),variants[0])
        play=next((v['play'] for v in variants if v['play']),None)
        summary=([c['summary'],c['summary_en']] if c.get('evidence_level')!='public_reader_metadata' else ['',''])
        works.append(dict(main,id=cid,category=c['category'],title=list(group[3]) if group else main['title'],
            summary=list(group[4]) if group else summary,play=play,variants=variants if group else [],
            tags=[tag for i in members for key in ('tags','tags_en') for tag in by_id[i][key]]))
    data={'categories':CATEGORY_NAMES,'works':works,'prompts':[
        {'title':[c['title'],c['title_en']],'source':c['source_url']} for c in prompts]}
    return {Path('site/catalog.js'):'// Generated by scripts/build.py; do not edit.\n'
        +'window.AI_FUN_CATALOG = '+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n'}
